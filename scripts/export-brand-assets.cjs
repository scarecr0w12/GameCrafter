#!/usr/bin/env node
// Editable brand geometry and reproducible vector/raster exports. No generated image is edited here.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const out = path.join(root, 'assets/brand');
const lime = '#BAFF2C';
const violet = '#120D1E';
const white = '#F7F4FF';
const ribbon = 'M48 160H120L176 300L232 160H280L336 300L392 160H464L362 400H310L256 272L202 400H150Z';
const spark = 'M256 32L273 84L320 100L273 116L256 168L239 116L192 100L239 84Z';
const mark = (color = lime) => `<path fill="${color}" d="${ribbon}"/><path fill="${color}" d="${spark}"/>`;
const svg = (w, h, content) => `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}" role="img" aria-label="PlayWeld">${content}</svg>\n`;
const word = (color, x, y, size) => `<text x="${x}" y="${y}" fill="${color}" font-family="Segoe UI,Arial,sans-serif" font-size="${size}" font-weight="700" letter-spacing="-3">PlayWeld</text>`;
const write = (name, data) => fs.writeFileSync(path.join(out, name), data);
async function main() {
  fs.mkdirSync(out, { recursive: true });
  write('mark.svg', svg(512, 512, mark()));
  write('mark-white.svg', svg(512, 512, mark(white)));
  write('mark-black.svg', svg(512, 512, mark(violet)));
  const icon = svg(1024, 1024, `<rect width="1024" height="1024" rx="224" fill="${violet}"/><g transform="translate(102 120) scale(1.6)">${mark()}</g>`);
  write('app-icon.svg', icon);
  write('logo-dark.svg', svg(1500, 400, `<g transform="translate(0 15) scale(.76)">${mark()}</g>${word(white, 410, 260, 190)}`));
  write('logo-light.svg', svg(1500, 400, `<g transform="translate(0 15) scale(.76)">${mark(violet)}</g>${word(violet, 410, 260, 190)}`));
  write('logo-white.svg', svg(1500, 400, `<g transform="translate(0 15) scale(.76)">${mark(white)}</g>${word(white, 410, 260, 190)}`));
  write('wordmark-dark.svg', svg(1180, 280, word(white, 10, 220, 220)));
  write('wordmark-light.svg', svg(1180, 280, word(violet, 10, 220, 220)));
  const banner = (w, h) => svg(w, h, `<defs><linearGradient id="bg" x2="1" y2="1"><stop stop-color="${violet}"/><stop offset="1" stop-color="#281A42"/></linearGradient><pattern id="grid" width="64" height="64" patternUnits="userSpaceOnUse"><path d="M64 0H0V64" fill="none" stroke="#B59FD2" stroke-opacity=".08"/></pattern></defs><rect width="${w}" height="${h}" fill="url(#bg)"/><rect width="${w}" height="${h}" fill="url(#grid)"/><g transform="translate(${w * .7} ${h * .15}) scale(${h * .0014})" opacity=".08">${mark()}</g><g transform="translate(${w * .06} ${h * .2}) scale(${h * .001})">${mark()}</g>${word(white, w * .06 + h * .58, h * .51, h * .19)}<text x="${w * .06 + h * .58}" y="${h * .64}" fill="#BFAED8" font-family="Segoe UI,Arial,sans-serif" font-size="${h * .055}">Your game development workspace.</text><text x="${w * .06 + h * .58}" y="${h * .79}" fill="${lime}" font-family="Segoe UI,Arial,sans-serif" font-size="${h * .045}">playweld.com</text>`);
  write('banner-wide.svg', banner(2400, 800));
  write('social-card.svg', banner(1200, 630));
  write('avatar.svg', icon);
  const generated = `// Generated by scripts/export-brand-assets.cjs. Edit geometry there.\nexport const PLAYWELD_RIBBON = '${ribbon}';\nexport const PLAYWELD_SPARK = '${spark}';\nexport const PLAYWELD_FAVICON = ${JSON.stringify('data:image/svg+xml,' + encodeURIComponent(icon))};\n`;
  const prettier = await import('prettier');
  const format = JSON.parse(fs.readFileSync(path.join(root, '.prettierrc'), 'utf8'));
  fs.writeFileSync(path.join(root, 'packages/theia-control-room/src/browser/brand-geometry.ts'), await prettier.format(generated, { ...format, parser: 'typescript' }));
  const { default: puppeteer } = await import('puppeteer');
  const browser = await puppeteer.launch({ headless: true });
  try {
    const page = await browser.newPage();
    const render = async (name, w, h, content) => {
      await page.setViewport({ width: w, height: h, deviceScaleFactor: 1 });
      await page.setContent(`<html><body style="margin:0;background:transparent">${content}</body></html>`);
      await page.evaluate(() => document.fonts.ready);
      await page.screenshot({ path: path.join(out, name), omitBackground: true });
    };
    for (const n of [16, 24, 32, 48, 64, 128, 180, 192, 256, 512, 1024]) {
      await render(`app-icon-${n}.png`, n, n, icon.replace('width="1024" height="1024"', `width="${n}" height="${n}"`));
    }
    for (const name of ['mark', 'mark-white', 'mark-black', 'logo-dark', 'logo-light', 'logo-white', 'wordmark-dark', 'wordmark-light', 'banner-wide', 'social-card']) {
      const source = fs.readFileSync(path.join(out, `${name}.svg`), 'utf8');
      const [, w, h] = source.match(/width="(\d+)" height="(\d+)"/);
      await render(`${name}.png`, Number(w), Number(h), source);
    }
    await render('brand-preview.png', 1600, 1060, `<svg xmlns="http://www.w3.org/2000/svg" width="1600" height="1060"><rect width="1600" height="1060" fill="${violet}"/><g transform="translate(70 70) scale(.95)"><g transform="scale(.76)">${mark()}</g>${word(white, 410, 260, 190)}</g><rect x="70" y="500" width="430" height="430" rx="84" fill="#21152F"/><g transform="translate(107 540) scale(.7)">${mark()}</g><rect x="560" y="500" width="970" height="430" rx="24" fill="#F7F4FF"/><g transform="translate(595 566) scale(.5)">${mark(violet)}</g>${word(violet, 880, 740, 105)}<text x="70" y="1010" fill="#BFAED8" font-family="Segoe UI,Arial,sans-serif" font-size="28">PLAYWELD / BRAND ASSET FAMILY / 2026</text></svg>`);
  } finally {
    await browser.close();
  }
  // ICO embeds the unmodified PNG frames; this is format packaging, not image editing.
  const frames = [16, 24, 32, 48, 64, 128, 256].map(size => ({ size, data: fs.readFileSync(path.join(out, `app-icon-${size}.png`)) }));
  const header = Buffer.alloc(6 + 16 * frames.length);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(frames.length, 4);
  let offset = header.length;
  frames.forEach(({ size, data }, index) => {
    const entry = 6 + 16 * index;
    header[entry] = header[entry + 1] = size === 256 ? 0 : size;
    header.writeUInt16LE(1, entry + 4);
    header.writeUInt16LE(32, entry + 6);
    header.writeUInt32LE(data.length, entry + 8);
    header.writeUInt32LE(offset, entry + 12);
    offset += data.length;
  });
  write('app-icon.ico', Buffer.concat([header, ...frames.map(frame => frame.data)]));
  fs.copyFileSync(path.join(out, 'app-icon.ico'), path.join(out, 'favicon.ico'));
  fs.copyFileSync(path.join(out, 'app-icon-180.png'), path.join(out, 'apple-touch-icon.png'));
  fs.copyFileSync(path.join(out, 'app-icon-192.png'), path.join(out, 'avatar.png'));
  console.log(`Exported editable SVGs and PNGs: ${out}`);
}
main().catch(error => { console.error(error); process.exitCode = 1; });
